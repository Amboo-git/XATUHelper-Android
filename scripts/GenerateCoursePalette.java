import palettes.TonalPalette;

/**
 * Generate CourseColors.kt with Google's Material Color Utilities Java sources.
 * Upstream: https://github.com/material-foundation/material-color-utilities
 * Revision: bd811e4ca2ab94c4ce3cadc89c19b1820b9704b3
 * Compile this file together with upstream java/{hct,palettes,utils}/*.java,
 * then run GenerateCoursePalette and redirect stdout to ui/CourseColors.kt.
 * No color-utility dependency is required in the Android application.
 */
public final class GenerateCoursePalette {
    private static final int[] HUES = {25, 265, 145, 85, 325, 205, 355, 235, 115, 55, 295, 175};

    public static void main(String[] args) {
        System.out.print("""
                package com.xatune.app.ui

                import androidx.compose.ui.graphics.Color

                data class CourseColors(val background: Color, val content: Color, val accent: Color)

                /**
                 * Generated by scripts/GenerateCoursePalette.java using Material Color Utilities.
                 * Twelve HCT hues, chroma 36; container/text/accent tones are 90/10/40 in
                 * light mode and 30/90/80 in dark mode. Independent of wallpaper colors.
                 */
                object CoursePalette {
                """);
        emit("light", 90, 10, 40);
        emit("dark", 30, 90, 80);
        System.out.print("""

                    /** Allocate from the whole semester, never just the visible week or hash remainder. */
                    fun indices(courseKeys: List<String>): Map<String, Int> = courseKeys.distinct().sorted()
                        .mapIndexed { index, key -> key to index % light.size }.toMap()
                }
                """);
    }

    private static void emit(String name, int background, int content, int accent) {
        System.out.printf("    val %s = listOf(\n", name);
        for (int i = 0; i < HUES.length; i++) {
            TonalPalette palette = TonalPalette.fromHueAndChroma(HUES[i], 36);
            System.out.printf("        CourseColors(Color(0x%08X), Color(0x%08X), Color(0x%08X))%s // HCT hue %d\n",
                    palette.tone(background), palette.tone(content), palette.tone(accent),
                    i == HUES.length - 1 ? "" : ",", HUES[i]);
        }
        System.out.print("    )\n");
    }
}
